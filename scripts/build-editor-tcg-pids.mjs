// Writes src/editor-tcg-pids.mjs: catalogue card id -> TCGplayer product id for the
// sets images.pokemontcg.io has no files for (me2pt5 and later). /data/editor/tcg
// uses it only after images.pokemontcg.io misses.
// An id gets a product id only from the catalogue row's own tcgPlayerId or from a
// one-to-one row in data/tcgcsv-to-catalogue.json (same set code, same number).
// Names are never a key. Usage: node scripts/build-editor-tcg-pids.mjs <Catchem-data dir>
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const DATA = process.argv[2];
if (!DATA) throw new Error("usage: build-editor-tcg-pids.mjs <Catchem-data dir>");
const SETS = ["me2pt5", "me3", "me4", "me5", "me55", "me55c", "me6"];
const read = async (p) => JSON.parse(await readFile(join(DATA, p), "utf8"));
const cards = (await read("data/card-catalogue.json")).cards;
const byCat = new Map();
for (const row of (await read("data/tcgcsv-to-catalogue.json")).mapped || []) {
  byCat.set(row.catalogueId, byCat.has(row.catalogueId) ? null : row.id);
}
const out = {};
for (const [id, c] of Object.entries(cards)) {
  if (!SETS.includes(c.setId)) continue;
  let pid = /^\d+$/.test(String(c.tcgPlayerId || "")) ? Number(c.tcgPlayerId) : 0;
  if (!pid) { const m = String(byCat.get(id) || "").match(/^tcgcsv-(\d+)$/); if (m) pid = Number(m[1]); }
  if (pid > 0) out[c.setId + "/" + id.slice(c.setId.length + 1)] = pid;
}
const keys = Object.keys(out).sort((a, b) => a.localeCompare(b, "en", { numeric: true }));
const body = keys.map((k) => `  ${JSON.stringify(k)}: ${out[k]},`).join("\n");
await writeFile(new URL("../src/editor-tcg-pids.mjs", import.meta.url), `// Generated by scripts/build-editor-tcg-pids.mjs. Do not edit by hand.
// Catalogue card id (set/number) -> TCGplayer product id, for sets with no
// images.pokemontcg.io files: ${SETS.join(", ")}.
export const EDITOR_TCG_PIDS = Object.freeze({
${body}
});
`);
console.log(`${keys.length} ids`);
