// Writes src/editor-tcg-pids.mjs: catalogue card id -> TCGplayer product id
// when images.pokemontcg.io has no file for that id. /data/editor/tcg uses
// the map only after images.pokemontcg.io misses.
// An id gets a product id only from the catalogue row's own tcgPlayerId or
// from a one-to-one row in data/tcgcsv-to-catalogue.json (same set code,
// same number). Names are never a key.
// Sets in SETS have no images.pokemontcg.io host at all (me2pt5 and later,
// plus mep). Other sets are included only for ids with no images.pokemontcg.io
// entry in card-images.json (mcd17, leftover svp, and any later gap).
// Usage: node scripts/build-editor-tcg-pids.mjs <Catchem-data dir>
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const DATA = process.argv[2];
if (!DATA) throw new Error("usage: build-editor-tcg-pids.mjs <Catchem-data dir>");
const SETS = ["me2pt5", "me3", "me4", "me5", "me55", "me55c", "me6", "mep"];
const read = async (p) => JSON.parse(await readFile(join(DATA, p), "utf8"));
const cards = (await read("data/card-catalogue.json")).cards;
const images = (await read("data/card-images.json")).images || {};
const hosted = (id) => {
  const u = images[id]?.large || images[id]?.small || "";
  try { return new URL(u).hostname === "images.pokemontcg.io"; } catch { return false; }
};
const byCat = new Map();
for (const row of (await read("data/tcgcsv-to-catalogue.json")).mapped || []) {
  byCat.set(row.catalogueId, byCat.has(row.catalogueId) ? null : row.id);
}
const out = {};
for (const [id, c] of Object.entries(cards)) {
  if (!SETS.includes(c.setId) && hosted(id)) continue;
  let pid = /^\d+$/.test(String(c.tcgPlayerId || "")) ? Number(c.tcgPlayerId) : 0;
  if (!pid) { const m = String(byCat.get(id) || "").match(/^tcgcsv-(\d+)$/); if (m) pid = Number(m[1]); }
  if (pid > 0) out[c.setId + "/" + id.slice(c.setId.length + 1)] = pid;
}
const keys = Object.keys(out).sort((a, b) => a.localeCompare(b, "en", { numeric: true }));
const body = keys.map((k) => `  ${JSON.stringify(k)}: ${out[k]},`).join("\n");
await writeFile(new URL("../src/editor-tcg-pids.mjs", import.meta.url), `// Generated by scripts/build-editor-tcg-pids.mjs. Do not edit by hand.
// Catalogue card id (set/number) -> TCGplayer product id, for ids with no
// images.pokemontcg.io file. Whole sets with no host: ${SETS.join(", ")}.
// Other sets appear only for the ids card-images.json does not host there.
export const EDITOR_TCG_PIDS = Object.freeze({
${body}
});
`);
console.log(`${keys.length} ids`);
