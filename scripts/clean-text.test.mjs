import assert from "node:assert/strict";
import { cleanText, cleanPage, money } from "../src/clean-text.mjs";
import { ensureAffiliation } from "../src/affiliation.mjs";
const Y = 2026;
assert.equal(money(540.3), "$540.30");
assert.equal(money(-19), "");
assert.equal(money("x"), "");
assert.equal(cleanText("Low $540.3 now", Y), "Low $540.30 now");
assert.equal(cleanText("$1,695.7", Y), "$1,695.70");
assert.equal(cleanText("$12.34", Y), "$12.34");
assert.equal(cleanText("CGC 10 after fees $-19", Y), "");
assert.equal(cleanText("query_error", Y), "");
assert.equal(cleanText("$NaN", Y), "");
assert.equal(cleanText("Down -$5.00 this week", Y), "Down -$5.00 this week");
assert.equal(cleanText("Date: 2026-10-15", Y), "Date: Oct 15");
assert.equal(cleanText("2025-10-16", Y), "Oct 16, 2025");
assert.equal(cleanText("Graded copies vary. data/enrichment-distilled.json, Aug 23, 2026", Y), "Graded copies vary. Aug 23, 2026");
assert.equal(cleanText("eBay ask $489.98, Oct 15, 2026. ebay-browse-api", Y), "eBay ask $489.98, Oct 15, 2026.");
assert.equal(cleanText("TCGplayer market via TCGCSV", Y), "TCGplayer market");
assert.equal(cleanText("Source: TCGplayer market via TCGCSV", Y), "Source: TCGplayer market");
assert.equal(cleanText("come from the public TCGCSV feed.", Y), "come from the public TCGplayer feed.");
const page = '<a href="/c/tcgcsv-1" data-d="2026-10-15">tcgcsv $5.5</a><script>var a="2026-10-15 $-1";</script><textarea>2026-10-15</textarea><p>after fees $-20</p>';
const out = cleanPage(page, Y);
assert.ok(out.includes('href="/c/tcgcsv-1" data-d="2026-10-15">TCGplayer $5.50</a>'), out);
assert.ok(out.includes('var a="2026-10-15 $-1"'));
assert.ok(out.includes("<textarea>2026-10-15</textarea>"));
assert.ok(out.includes("<p></p>"));
assert.ok(ensureAffiliation("<main><h1>x $3.1</h1></main>").includes("$3.10"));
console.log("clean-text ok");
